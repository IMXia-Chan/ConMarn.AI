package com.example.touchpad

/**
 * 「跟她说话」这件事里**不该靠猜**的那几个判断。
 *
 * ## 为什么值得单独一个文件
 *
 * [Ear] 管的是「一句话怎么变成文字」——那是一锤子买卖,错了当场看得出来。
 * 这个文件管的是**一轮接一轮**的时候才冒出来的错,而那一类错的共同点是
 * **都不报错,只是对话卡住了或者断掉了**:
 *
 * | 会坏的样子 | 看起来像 | 真因 |
 * |---|---|---|
 * | 她念完没把麦放回来 | 她不理我了 | 循环断了 |
 * | 她压根没出声(嗓子关着),还在等 `onDone` | 她不理我了 | 等一个永远不会来的回调 |
 * | 她把自己念的话听成用户输入 | 她自问自答 | 半双工没做 |
 * | 「跟他说再见」被当成挂断 | 对话莫名其妙断了 | 本地判据太贪 |
 *
 * ## 两条贯穿这个文件的取向
 *
 * **① 判据不对称:挂断要严,继续要宽。** 漏判一句「不聊了」的代价是**多听一轮**
 * (她顶多把这句话当普通话说一句,轻微);误判的代价是**对话突然中断**,
 * 而用户会以为坏了。所以 [isExitPhrase] **不做「包含」也不做「结尾是」**那套 ——
 * 它只剥掉句首的垫词和句尾的语气助词,剩下的**必须是整句等于**。
 * 2026-10-05 那一次把口子开到这里,是因为用户点名两句被挡在外面:
 * 「那你先退下吧」「退出」。(见 [isExitPhrase] 那段)
 *
 * **② 凡是「等一个回调」的地方都必须有上限。** `onDone` 是 TTS 的回调,
 * 而 `speak()` 在**嗓子关着**的时候是直接 return 的 —— 它一辈子都不会来。
 * 没有上限的话,症状就是她说完上一句之后永远沉默,零报错。
 */
internal object EarSessionMath {

    /**
     * 她念完之后、重新开麦之前的那一下停顿。
     *
     * ★ 不是可有可无的礼貌。扬声器出来的声音在房间里还有余响,而这台机器是
     *   **外放**;`onDone` 回来的那一刻尾音还没散干净。立刻开麦的话,
     *   最后半个字会被听成一句新输入 —— 那正是自问自答最典型的入口。
     */
    const val COOLDOWN_MS = 300L

    /**
     * 从「把话送进脑子」到「必须重新开麦」的上限。
     *
     * ★ 这个数字覆盖的失败比它看起来多:她的回复出错([AiAgent.Callback.onError])、
     *   TTS 引擎没初始化好、有人把「出声」那个开关关了 ——
     *   这四种情况下 `onDone` **一个都不会来**。没有这条兜底,循环就死在这一轮。
     *   宁可等久一点再放麦:等待的代价是她偶尔抢一句,卡死的代价是整场对话没了。
     */
    const val SPEAK_MAX_MS = 90_000L

    /**
     * 这一轮该等她的声音多久。
     *
     * ★★ `willSpeak == false` 时返回 **0** 是这个文件里最要紧的一条。
     *   嗓子关着 / 引擎没就绪时,等 90 秒兜底就等于**每一轮都空转 90 秒** ——
     *   用户看到的是「她说了一句,然后死机一样不理我了」,而日志里一片太平。
     *   **明知道她不会出声,就一秒都不能等。**
     */
    fun speechWaitMs(willSpeak: Boolean): Long = if (willSpeak) SPEAK_MAX_MS else 0L

    /** 她念完了,再等这么久就该开麦了。 */
    fun resumeAt(nowMs: Long): Long = nowMs + COOLDOWN_MS

    /**
     * ★★ **她的嗓子空了没有** —— 半双工闸的总判据。
     *
     * 用户 2026-10-05 原话,和日志里量到的**一模一样**:
     * > 「她还没说完,系统就误认为她说完,就打开麦克风,然后她就自己跟自己聊起来了」
     *
     * 日志原样(21:00:28~21:01:37):她说「行,我记下了。」→ 两秒后麦克风把**这句**
     * 转写成了「他说的」→ 她照着答了一句 → 一分钟后又把它当他的话引用了一遍。
     *
     * ## 为什么只问「正在出声吗」是不够的
     *
     * 因为 `speaking` 的意思是**正在出声**,不是**还有话要说**:
     *
     * | 她在干什么 | `speaking` | 队列里还有吗 |
     * |---|---|---|
     * | 正在念 | true | 可能还有 |
     * | ★ **正在合成下一句** | **false** | ★ **有** |
     * | 真的说完了 | false | 没有 |
     *
     * 中间那一行是整件事的要害:这台机器上合成**比实时慢**(实测实时倍率 0.35×~0.79×),
     * 一句 20 个字要造十几秒(日志里排队等待到过 **18177ms**)。那十几秒里
     * 一点声音都没有,只看 `speaking` 就以为她说完了 —— 于是开麦,
     * 而她下一句一开口,每个字都绕回自己的麦克风。
     *
     * ★ 两个条件缺一不可,**别只留一个**:
     *   · `pendingChunks` 里含**正在念的那一句**(它在跑完时才销账),
     *     所以「队列空」不等于「她闭嘴了」;
     *   · 而 `speaking` 在两次出声之间会短暂为 false(换句那一下),
     *     那一下就够麦克风抓半句话。
     */
    fun herVoiceFinished(speaking: Boolean, pendingChunks: Int): Boolean =
        !speaking && pendingChunks <= 0

    /**
     * ★★ 整场对话**总共**能安静多久 —— 用户 2026-10-04 点名的那个 45 秒。
     *
     * 原话:「说完话她说,她说完自动听我说,**我 45 秒内没说话,就自动关闭麦克风**,
     * 如果说了话,她听,听完再思考再和我对话,然后重复这种步骤」。
     *
     * ## 它和 [Ear] 里那个 5 秒是什么关系(别搞混,这两个数管的是两件事)
     *
     * | | 管什么 | 到点了怎么办 |
     * |---|---|---|
     * | `Ear.IDLE_GIVEUP_MS` = 5s | **一轮**里没人开口 | 这一轮收工 |
     * | `SESSION_SILENCE_MS` = 45s | **整场**累计安静了多久 | 对话结束,麦关掉 |
     *
     * ★ 这一条是**这一版真正的修复**。在这之前根本没有「整场」这个概念:
     *   一轮 5 秒没人声 → `onDone` → `heardThisTurn == false` → 直接
     *   `endVoiceSession()`。于是他说话稍一停顿,对话就断了,而症状是
     *   「**她说了两句就不理我了**」——看起来像她坏了,其实是**我们只给了 5 秒**。
     *   他要的 45 秒得**在这上面再套一层循环**才存在。
     *
     * ## 为什么从「听到东西」那一刻重新数,而不是从「开麦」那一刻
     *
     * 因为他说话的**速度**不该被计费:一句长话说到 40 秒才停,那 40 秒里
     * 麦克风一直在收音,不该算进「没说话」。计时器跟着**最后一条真实动静**走。
     *
     * ⚠️ 45 秒是**他给的数**,别自作聪明改小。它的作用恰恰是「允许你想一下再说」——
     *   调小就等于把他那句话又变成 5 秒那版。
     */
    const val SESSION_SILENCE_MS = 45_000L

    /**
     * 安静了 [silentMs] 这么久,这场对话就该收了。
     *
     * ★ 判据用 `>=` 而不是 `>`:边界在测试里要钉得死。
     *   44499 不算、45000 算 —— 和 [com.example.touchpad.EarMath] 那几条时长用例同一个规矩。
     */
    fun sessionOver(silentMs: Long): Boolean = silentMs >= SESSION_SILENCE_MS

    /**
     * 手指按住多久之上算「按住说话」,之下算「点一下」。
     *
     * ## 为什么需要一个门槛,而不是「点 = 打断 / 按住 = 说话」两个手势各判各的
     *
     * 用户在**同一个东西**上要了两个动作(原话:「我打断她,就点那个光晕字幕就打断了」+
     * 「我说话的时候按住那个动态光晕,就开始说话」)。手指按下去的那一刻,
     * **没人知道他想干哪一件** —— 只有等他松开,才知道这一下是长是短。
     *
     * 所以时序必须是:**按下先不开麦 → 松开时看按了多久 → 短 = 打断,长 = 说话**。
     * 反过来的话(按下就开麦),每一次「点一下打断她」都会先**把麦克风打开**再关掉 ——
     * 屏幕上会闪一下「我在听」,而**那是在撒谎**。
     *
     * ★ 350ms 的取法:比双击间隔(系统 300ms)略长,比人「按住」的自然时长(>500ms)短。
     *   它是**手感**,不是安全边界 —— 偏一点只是偶尔要再按一次,不会做错事。
     */
    const val TAP_MAX_MS = 350L

    /** 这一下按得算「点一下」还是「按住说话」。 */
    fun isTap(heldMs: Long): Boolean = heldMs < TAP_MAX_MS

    /**
     * 松手了,还要不要等 VAD 自己断句。
     *
     * ★ **不等。** 按住说话的语义就是「我松手 = 我说完了」——
     *   再让 [Ear] 空等 5 秒 VAD,他会以为是卡了(而这台机器上他真的会以为卡了,
     *   因为他刚刚才为「说了话没反应」找过我)。
     */
    fun shouldFinishOnRelease(heldMs: Long): Boolean = !isTap(heldMs)

    /**
     * 本地判「他在说挂断」。
     *
     * ★★ 2026-10-05 用户点名两句被挡在门外:
     *   > 「还有就是,我说『**那你先退下吧**』,『**退出**』等等,就关闭麦克风模式」
     *   第一句按老判据是**必然失效**的:「那你先退下吧」六个字,而词表里只有「退下吧」。
     *   而这正是他**最自然**的说法 —— 一句判据挡掉最自然的说法,等于这个功能没做。
     *
     * ★ 放宽的方式**不是**「包含」也不是「结尾是」,而是**剥垫词再整句对**:
     *   句首剥掉称呼/语气垫词([FILLER_HEAD]),句尾剥掉语气助词([FILLER_TAIL]),
     *   剩下的**必须一字不差地等于**词表里的某一条。
     *
     *   「那你先退下吧」→ 剥「那」「你」「先」→ 剥「吧」→ **「退下」** ✓
     *   「跟他说再见」  → 句首「跟」不是垫词,**一个字都不剥** → 不中 ✓
     *   「行了不聊了」  → 句首「行」不是垫词,**一个字都不剥** → 不中 ✓
     *
     * ★ 为什么这样是安全的:垫词是**封闭的一小组**,而且只从**两头**剥。
     *   句子里任何一个**实词**(「跟」「行」「说」「让」)只要出现在垫词之外,
     *   剥的动作当场停住,那句话就永远不中。
     *   这正是它和「结尾是」的区别 —— 后者对**句子中间**发生的事一无所知。
     *
     * ★ 两条**故意**漏掉的,一条都不能认(见 [EXIT] 上面的注释):
     *   · 「跟他说再见」—— 那是让他去操作电脑,不是跟我们挂断
     *   · 「不用了」—— 那多半是在回答她的问题(「要我帮你打开吗?」),不是要走
     *   漏掉它们 = 多聊一轮;认下它们 = 对话在她最需要继续的时候断掉。
     */
    fun isExitPhrase(raw: String): Boolean {
        // ★ 用的是「只留字」而不是「去掉标点」。
        //   看着是一回事,其实差在**枚举不完**上:要「去掉标点」就得把全角句号、
        //   问号、省略号、间隔号、波浪号一个一个列全,漏一个就是
        //   「不聊了～」不生效 —— 而那看起来像「她装没听见」。
        //   反过来只认字母和数字,标点/符号/空白/表情**不用认识就全被挡在外面**。
        //   (中文表意文字在 `isLetterOrDigit` 里是 true —— 见 EarMathTest 那条钉过的用例。)
        val t = raw.filter { it.isLetterOrDigit() }
        if (t.isEmpty()) return false
        // ★ 先试原句。这一步不能省:剥垫词是**单向**的,
        //   「不说了」剥掉句尾的「了」会变成「不说」—— 原句明明在词表里,
        //   却因为多剥了一下而落空。先认原句,再谈宽容。
        if (t in EXIT) return true
        val s = t.trimStart { it in FILLER_HEAD }.trimEnd { it in FILLER_TAIL }
        return s.isNotEmpty() && s in EXIT
    }

    /**
     * 句首的**垫词** —— 剥掉它们不改变这句话的意思。
     *
     * ⚠️ 这是**白名单**,不是「随便剥几个字」。每多一个字,就多一句话可能被误判成挂断,
     *   而误判的代价是对话突然断掉(见文件头第 ① 条)。
     *   所以这里只放称呼和语气词:**实词一个都不许进来**
     *   —— 「跟」「行」「让」「说」这类一旦进来,「跟他说再见」当场变成挂断。
     */
    private val FILLER_HEAD = "那你就我先好嗯哦唉哎喂了"

    /**
     * 句尾的**语气助词** —— 剥掉它们只是让「退下吧」「结束了吧」这类口吻落回词表。
     *
     * ⚠️ 同样只放语气词。「了」放进来是为了「结束了吧」,而它**不会**伤到
     *   「不说了」「没事了」这类 —— 那些句子在 [isExitPhrase] 的第一步(试原句)
     *   就已经有结论了,轮不到这里;而它们本来就**不在**词表里,该是 false 还是 false。
     */
    private val FILLER_TAIL = "吧啊呀哦呢啦嘛咯喔了"

    /**
     * 挂断词表。
     *
     * ⚠️ 这个项目在这件事上栽过:规则快通道(`FastPath`)曾经把「在手机上打开相机」
     *   抠成「打开电脑上的相机」,而 Windows 真有个叫「相机」的应用 ——
     *   它**成功地**做错了事,于是永远走不到「失败就交回模型」那条兜底。
     *   同一个教训:**认识的话越少,能犯的错越少。**
     *
     * ★ 加词之前先问自己两件事:
     *   ① 这句话会不会是他在**回答她的问题**(「不用了」就是这么被挡在外面的)?
     *   ② 它会不会是**给她的指令**(「跟他说再见」是让她去操作电脑)?
     *   两条中任一条答「会」,就不加。
     */
    private val EXIT = setOf(
        "不聊了", "不聊啦", "不说了",
        "再见", "拜拜",
        "退下", "退下吧",
        "结束", "结束吧",
        "退出",                 // 2026-10-05 用户点名要的
    )

}
