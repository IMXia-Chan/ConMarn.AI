package com.example.touchpad

/**
 * 「这一屏上没有那个名字」之后,**该不该去用这个界面自己的搜索**。
 *
 * ---------------------------------------------------------------------------
 * ★★ 这一条是从**真机日志**里读出来的(2026-10-08),不是推测。用户的原话是:
 *
 *   > 「有点问题,关微信的时候,我让她关微信她就在搜索框中关微信」
 *
 * 日志里逐行对上(19:39:07–19:39:13):
 *
 *   球: → 执行 click_ui {"name":"关闭"}
 *   球: 「关闭」不在这一屏上(认得出 11 行字,但里头没有它)—— 查经验库…
 *   球: 先直接再看一眼(可能只是画面没准备好)…
 *   球: 经验库:用这个界面自己的搜索找「关闭」…      ← ★ 就是这一句
 *   球: 点到了(靠经验「search → scroll → visual」,现在置信度 88%)
 *
 * ---------------------------------------------------------------------------
 * ★★ 为什么「关窗口」这类词**不能**走 search:
 *
 * `search` 这个动词做的事,是**把词打进那个应用自己的搜索框**(普通应用 Ctrl+F,
 * 浏览器走地址栏)。它成立的前提是:**这个目标是那个应用里的一条内容** ——
 * 文件、会话、联系人、网页。而「关闭 / 退出 / 最小化」**不是内容,是动作**:
 * 它要作用在**窗口本身**上,那个应用里根本没有一样东西叫这个名字,搜一万遍也没有。
 *
 * 所以对这类词走 search 是**双重错**:
 *
 * 1. 找不到(它本来就不在里面);
 * 2. ★ **在用户的 App 里凭空打了两个字** —— 而用户看到的就是这个:
 *    微信的搜索框里冒出来「关闭」。
 *
 * 更糟的是它**还可能报成功**:刚打进搜索框的那行字被 `retryFind` 当成了命中,
 * 于是这条坏策略的置信度**不降反升**(日志里 88% → 89%)。
 * 「越用越强」那套机制被喂了一个谎,坏办法越用越"可信"。
 *
 * ---------------------------------------------------------------------------
 * ★ 判据是**封闭词表 + 精确匹配**,两条都是故意这么定的:
 *
 * | 怎么定 | 为什么 |
 * |---|---|
 * | **词表**,不是形状规则 | 这个项目的老规矩 —— **「形状会撞,表不会」**(同 [EphemeralMath] 的敏感控件词表) |
 * | **精确匹配**,不做前缀 | 这条是**「宁可漏不可错」**:一个叫「关闭按钮设计稿.txt」的文件**是**真内容,搜它是对的。做前缀匹配会把它一起误伤,而这里误伤一次的代价是**那个目标永远点不到**(比多搜一次糟得多) |
 *
 * 所以边界是清楚的:**只拦「整个名字就是一句窗口命令」**。「关闭按钮」这种
 * 长得像、但是内容的,走原来那条路。
 *
 * ★ 它**自己不改任何能力** —— 它只负责「别把这两字打进搜索框」。
 *   拦住之后往回带一句话:**改用 hotkey(alt+f4)**(那个动作是 2026-10-08 用户
 *   拍板给的,见 `ai_tools.py` 的按键白名单),见 [AiAgent.resolveMiss] 那一小段。
 *   ★ 分工要清楚:**判据在这儿,动作在别处** —— 别让这个文件长出「顺手替她关」的代码。
 */
internal object MissMath {

    /**
     * 「就是一句窗口命令」的那些词 —— **封闭集合,精确匹配**。
     *
     * ★ 只收**整个名字等于它**的;不收「以它开头」的(理由见文件头)。
     * ★ 英文那几个一并收了:这台机器上界面是中文的,但模型偶尔会直接吐英文动词。
     */
    private val WINDOW_COMMANDS: Set<String> = setOf(
        // —— 关 ——
        "关闭", "关掉", "关上", "关窗口", "关闭窗口", "关闭这个窗口", "关闭当前窗口",
        // —— 退 ——
        "退出", "退出程序", "退出应用", "退出软件", "退出游戏",
        // —— 窗口操作 ——
        "最小化", "最小化窗口", "最大化", "最大化窗口",
        // —— 英文 ——
        "close", "closewindow", "quit", "exit", "minimize", "maximize",
    )

    /**
     * 这个名字是不是「对窗口本身下手」,而不是「在这个界面里找一行字」。
     *
     * true ⇒ 调用方**不该**再走 search/滚屏那一套,应当诚实地说做不到。
     */
    internal fun isWindowCommand(name: String): Boolean = normalize(name) in WINDOW_COMMANDS

    /**
     * 抹掉那些「人写的时候有、当判据的时候没有」的东西。
     *
     * ★ 两个都踩过:
     * - **空白**:模型有时写成「关 闭」「关闭 窗口」,或者前后带空格。
     *   用户心里它们是同一个词,判据里也该是。
     * - **包在外面的引号/书名号/括号**:名字被写成「关闭」「`关闭`」是常事
     *   (提示词里到处是「」,它照着学)。
     */
    private fun normalize(raw: String): String {
        val wrapped = raw.trim().trim(*WRAPS)
        return wrapped.filterNot { it.isWhitespace() }.lowercase()
    }

    /** 包在名字外面、不参与判定的那圈符号。 */
    private val WRAPS = charArrayOf(
        '「', '」', '『', '』', '“', '”', '\'', '"',
        '《', '》', '(', ')', '（', '）', '【', '】',
        '[', ']', '{', '}', '<', '>',
        ',', '，', '.', '。', '!', '！', '?', '？', ':', '：', ';', '；',
    )
}
