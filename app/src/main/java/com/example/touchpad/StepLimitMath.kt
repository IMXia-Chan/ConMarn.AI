package com.example.touchpad

/**
 * 「步数到顶了,模型还不肯收口」—— **纯逻辑,零 Android 依赖,能跑 JVM 单测。**
 *
 * ## 它治的是什么
 *
 * `runLoop` 的规矩是:工具调满 [maxSteps][com.example.touchpad.AiAgent.Config.maxSteps] 次,
 * 就往 messages 里写一条「不能再调工具了,请直接说明情况」的回执,然后**再给模型一轮**。
 * 守规矩的模型下一轮改说人话,正常收工。
 *
 * 不守规矩的 4B 会**无视那句回执,继续吐 tool_calls**。原来的循环没有任何总轮数上限:
 * `while (true)` 一轮接一轮地跑,每轮 messages 再长一截(一条 tool_calls + 一条回执),
 * 每轮一次完整的模型请求。它最终当然会停 —— 等上下文撑爆、服务端报错、异常冒出来 ——
 * 但在那之前是**十几轮无产出的满载请求**,在这台手机上就是几分钟的 CPU 和热。
 * 而 UI 上她看起来只是「想了特别久」。
 *
 * ## 判定的形状:提醒 → 重申 → 强制收口
 *
 * - 第 1 次撞上限:写回执(提醒)。这是**给模型机会** —— 4B 听一次就改口是完全正常的。
 * - 第 2 次撞上限(它无视了提醒):再写一遍(重申)。重复一遍对小模型的指令遵循
 *   真的有用,这一轮不贵。
 * - 第 3 次撞上限:**不再写了** —— 它已经被明说两遍还在继续,第三遍大概率还是一样。
 *   由调用方直接替她收口:返回 [finalSay] 那句话作为本轮的最终答复,循环终止。
 *
 * ## 收口那句话的两条规矩(由单测钉着)
 *
 * 1. ★ **不许说「做完了」。** 这一轮**就是**没做完才停的 —— 收口的话必须明说停了。
 * 2. ★ **不许把责任推给他。** 是模型的循环被掐断,不是「你让我做的事太多」。
 */
internal object StepLimitMath {

    /**
     * 回执最多写几遍。
     *
     * ★ 2 = 「一条提醒 + 一条重申」,第 3 次撞上来就收口。
     *   调大 = 更有耐心,代价是病态循环里多烧几轮满载请求;
     *   调成 1 = 提醒一次就掐,掐掉的是**本来下一轮就会改口的模型** —— 那是误伤。
     */
    internal const val MAX_NOTICES = 2

    /**
     * 第 [notices] 次撞步数上限了 —— 该强制收口了吗。
     *
     * ★★ **半开语义**(和 `HandoffMath.mayKeepWaiting` 同一套写法):
     *    恰好等于 [MAX_NOTICES] 时**仍然给机会**(第二条回执照写);
     *    超过它才收口。边界只属于一边,测试钉死。
     */
    internal fun giveUp(notices: Int): Boolean = notices > MAX_NOTICES

    /**
     * 强制收口时,她说出口的那句话(会进字幕和嗓子,不是日志)。
     *
     * ★ 平、短、不表演 —— 她的语气是他自己调的(见 `conmarn-persona-is-his-to-tune`),
     *   这里只负责把事实说对:停了、办成的不受影响、请他说下一步。
     */
    internal fun finalSay(): String =
        "这一轮做的步骤太多,到了上限我还想接着做,就先停在这儿了。已经办成的不受影响——你说下一步怎么办。"
}
