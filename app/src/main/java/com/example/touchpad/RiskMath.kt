package com.example.touchpad

/**
 * 三层风险闸的**第一层**:「这一轮该不该一路问下去」—— **纯逻辑,零 Android 依赖,能跑 JVM 单测。**
 *
 * ## 它治的是什么
 *
 * 用户 2026-10-05 最烦的那句话是「**她会乱动电脑**」。而今天全项目**没有一处**在动手之前问一句:
 * 点一下、按一次回车,直落电脑。她能做到的事 = 你坐在电脑前能做的事,**没有第二个人的手拦一下**。
 *
 * ## 为什么第一层必须存在(第二层接不住它)
 *
 * 一条真正花钱的路,**每一步单独看都不危险**:
 *
 * ```
 * 点联系人 → 点「+」→ 点「转账」→ 输金额 → 点「确认」      ← 第 5 步才见血
 * ```
 *
 * 前四步的控件名字叫「+」「确认」,和别的地方的「+」「确认」长得一模一样。
 * 逐动作判名字**抓不住它**。所以必须在**任务刚开始**的时候就认出「这是一件碰钱的事」,
 * 认出之后这一轮里每一次动手都要他点一下。
 *
 * ## 判据是确定性的,不让模型判
 *
 * 关键词匹配,不是「问 4B 这危不危险」。理由有两条,都不是风格问题:
 * ① 4B 判风险稳不住(项目里已经有同款结论:不抄「让模型在 tool_call 里多吐一个风险字段」那套);
 * ② **这条判据是安全承重墙,它必须能被单测钉死** —— 一个会变的模型判不了「一定不会漏」。
 *
 * ## ★★ 名单里放什么:**只认钱和身份类词**(2026-10-05 用户当场定的)
 *
 * 我原本照计划把「微信 / 支付宝 / 淘宝」这类**应用名**也算了进去,他选了窄的那一档。
 * 这个选择是对的,理由值得记住 —— **一条会被关掉的安全功能等于没有**:
 *
 * | | 宽的那档(应用名也算) | **他选的这档(只认钱和身份)** |
 * |---|---|---|
 * | 「打开微信」 | 整轮每一下都要点头 | ★ 照旧直接干活 |
 * | 「给文件传输助手发一条」 | 整轮每一下都要点头(**他每天在用**) | ★ 照旧直接干活 |
 * | 「给张三转 50」 | 每一下都要点头 | ★ **每一下都要点头** |
 *
 * 两档在**该拦的那件事上完全一样**,差别只在日常用的那些会不会被一起拖下水。
 * 所以这里收窄不是妥协,是**把力气全花在真会花钱的那几句上**。
 *
 * ★ 名单**只能由用户改**(他改了算)。别的地方没有第二条修改路径,
 *   更**绝不能被外部内容改写**(网页、被点开的 App、模型自己都不行)——
 *   反面教材是 `Aider CVE-2026-85674`:自动加载仓库根的配置文件、无确认执行,
 *   于是 clone 一个恶意仓库就是任意代码执行。**能被外部内容改的名单等于没有名单。**
 */
internal object RiskMath {

    /** 这一轮的风险档。 */
    enum class Tier { NORMAL, HIGH }

    /**
     * **钱**和**身份**这两类词 —— 出现任何一个,这一轮进高危档。
     *
     * ★ 收录的标准只有一条:**这个词一旦真的发生了,是收不回来的**。
     *   转出去的钱、发出去的红包、提交掉的订单、泄露的密码和验证码 —— 都没有「撤销」。
     *   所以「查询」「看看」这类词不收(它们不改变任何东西)。
     *
     * ★ 收窄时的判断依据(见文件头那张表):一个词会把多少**日常不危险的**用法拖进来。
     *   「微信」被去掉就是因为这个 —— 它单独出现时不代表任何事要发生。
     */
    private val MONEY_AND_IDENTITY = listOf(
        // ── 钱,动一下就出去了 ──
        "转账", "汇款", "打钱", "转账给", "付款", "支付", "买单", "付钱",
        "红包", "发红包", "提现", "充值", "下单", "结算", "收款", "收钱",
        "还钱", "还款", "还花呗", "花呗", "信用卡", "银行卡", "余额",
        "理财", "基金", "股票", "证券", "贷款", "借款", "借钱", "工资",
        // ── 身份,泄露就换不回来 ──
        "密码", "验证码", "身份证", "实名认证", "人脸识别", "短信验证",
    )

    /**
     * ★★ **单说一个字不成话、但配上钱数就成话**的词。
     *
     * 这是为了堵一个真实的洞:**最自然的说法根本不带「转账」两个字** ——
     * 「给张三**转 50**」「**转五万**给他」。上面那张表里一个都对不上,
     * 而它们说的是同一件事。这个洞是我自己写在文件头当例子的那句,不能留着。
     *
     * ## 判据:**光有这个词不算,还得有一笔钱的样子**
     *
     * 一个字加一个数字/钱数单位才算数。这条界线是拿失败代价划的:
     *
     * | | 判成高危 | 结果 |
     * |---|---|---|
     * | 「转成 PDF」「翻译成英文」 | ✗(没有钱的样子) | ★ 照旧直接干活 —— **不要误伤他天天在用的那些** |
     * | 「转 50」「转五万」 | ✓ | 一路点头。**烦,但那是钱** |
     *
     * ★ 它会漏吗?会:「转五十」里「五十」是汉字、单位也没有 —— 漏。
     *   但**漏的方向由下一层接住**(电脑侧的动作级兜底 + 键盘那一下的确认闸),
     *   而按「宁可漏不可错」的老规矩:这一层宁可**多问**,不许**少问**。
     */
    private val NEEDS_AMOUNT = listOf("转", "付", "充", "退")

    /** 钱的样子:阿拉伯数字,或者钱数的量词。★ 全角数字也算(`isDigit` 认)。 */
    private val MONEY_MARKS = listOf("块", "元", "万", "千", "百", "毛", "角")

    /**
     * 高危档下,**碰鼠标键盘**的动作。
     *
     * ★ `click_element` 也在里面:它是「截图 → 视觉模型看图 → 点坐标」那条兜底路,
     *   最后**真的会动鼠标**(它内部走 `callPc("click_at")`)。名字听起来像「看看」,
     *   所以最容易漏 —— 而漏了它的表现是「这条路不用点头」,日志上什么都看不出来。
     */
    private val TOUCH_TOOLS = setOf("click_at", "click_ui", "click_element", "hotkey", "search")

    /**
     * 这一句用户指令属于哪一档。
     *
     * @return [Tier.HIGH] = 这一轮里每一次动手都要他点头。
     */
    internal fun taskTier(userText: String): Tier =
        if (matchedWord(userText) != null) Tier.HIGH else Tier.NORMAL

    /**
     * 命中的是哪个词(**给用户看的那句「为什么要一路问」用的**),没命中回 null。
     *
     * ★★ 它**故意只回命中的那个词,不回原句**。原句是用户自己打的,里面完全可能
     *   带着一串验证码(「把验证码 123456 打进去」)—— 而那串数字**绝不能回显**。
     *   回一个「验证码」三个字,既说清了原因,又不可能把敏感的东西带出来。
     */
    internal fun matchedWord(userText: String): String? {
        MONEY_AND_IDENTITY.firstOrNull { userText.contains(it) }?.let { return it }
        if (!looksLikeMoney(userText)) return null
        return NEEDS_AMOUNT.firstOrNull { userText.contains(it) }
    }

    /** 这句话里有没有「一笔钱」的样子。 */
    private fun looksLikeMoney(s: String): Boolean =
        s.any { it.isDigit() } || MONEY_MARKS.any { s.contains(it) }

    /**
     * 这个动作在高危档下要不要他点一下。
     *
     * ## 为什么是这几个
     *
     * 「碰鼠标键盘」= 真的会改变电脑上的状态的四个。
     *
     * ★ **`scroll` 故意不在里面。** 它不动任何东西 —— 问它一次只是让他烦一次,
     *   而按项目的老规矩「宁可漏不可错」在这里要反过来读:**代价不对称的方向变了**。
     *   漏问一次滚动,代价是零;多问一次滚动,代价是他把这个开关关掉。
     *   (滚动本身仍然过电脑侧那道焦点守门,见 `_guard_focus`。)
     *
     * ★ **`type` 也不在里面,但不是放过它** —— 它**本来就每次都问**,而且是全项目
     *   唯一一道现成的、绑内容的确认闸(见 `dispatch` 里那一段)。
     *   放进来的话一次打字会弹两个框,那比不问还糟:人会开始闭着眼点。
     *
     * ★ **`open_app` / `focus_window` 不在里面**:它们决定焦点在哪,不往里面送东西。
     *   真正危险的是**在**那个窗口里做的事,而那些事在上面这四个里。
     *
     * ⚠️ **以后加新的写工具(比如 `set_value`),必须加进 `TOUCH_TOOLS`。**
     *    电脑侧的白名单(`_GUARDED_TOOLS`)就吃过这个亏 —— **新工具不在名单里 = 完全没有守门**,
     *    而且不报错。
     */
    internal fun needsTap(tier: Tier, tool: String): Boolean =
        tier == Tier.HIGH && tool in TOUCH_TOOLS

    /** 他要点的那一下,标题上写什么。**按动作分,不按工具名分** —— 他看的是人话。 */
    internal fun tapTitle(tool: String): String = when (tool) {
        "click_at", "click_ui" -> "确认点这一下"
        // 视觉那条路要先花几分钟看图,他会看到「她想了很久」—— 标题里说破,
        // 否则他会以为是她卡住了,而不是「在等你点头/在看图」。
        "click_element" -> "确认点这一下(要先看图,慢)"
        "hotkey" -> "确认按这个键"
        "search" -> "确认搜索"
        // ★ 打字这一个**第一层永远走不到**(`type` 不在 [TOUCH_TOOLS] 里 —— 它本来
        //   就每次都问,见 [needsTap] 的说明)。但**第二层拦得到它**:焦点在银行那类
        //   应用上时,往里面打任何字都会被拦下。那时框里要是只写一个「确认」,
        //   他看到的是一句没头没脑的话。用**和打字那道闸一模一样的措辞**,
        //   他一眼就知道这是同一件事,不会以为是两个框。
        "type" -> "确认输入文字"
        else -> "确认"
    }

    // ═══════════════════════════════════════════════════════════════════════
    // ★★ 第三层(手指)—— 电脑说「这一步得人来点」之后,手机这边怎么办
    //
    // 这一层的**判定**在电脑那边:焦点在谁身上、要点的那个控件叫什么名字 ——
    // 都是只有它才看得见的事实。手机这边只拿得到**一句回执**,所以这里要判的
    // 只有一件事:**这句话是什么意思,我该做什么。**
    //
    // 为什么它也得是纯函数、也得有单测:它的失效方式**全是静默的** ——
    // 拼错一个字符串,这道闸就再也不响了;多问一轮,他就开始闭着眼点了。
    // 两种都不会报任何错,只表现为「某天开始不对了」。
    // ═══════════════════════════════════════════════════════════════════════

    /**
     * 电脑回执里「这一步得人来点」的标记。
     *
     * ★★ 它是一份**跨端契约**:`pc-server/ai_tools.py` 回的就是这个字面量。
     *   两边拼不成一模一样的字,这道闸就**永远不响**,而且不报错 ——
     *   和工具表漂移是同一类病(`eval/check_tool_drift.py` 守的就是那个),
     *   所以这个字符串也有测试钉着。
     */
    internal const val NEEDS_CONFIRM = "needs_confirm"

    /** 拿到一条电脑回执之后,手机侧该做什么。 */
    enum class Tap {
        /** 电脑没提这回事 —— 原样交回去。 */
        PASS,

        /** 电脑说这一步要人点一下,而**还没问过** → 弹框;他点头就带着凭证重发一次。 */
        ASK_THEN_RETRY,

        /** 问过了、他也点了头,电脑还是说做不了 → **不许再问**,把原话交回去。 */
        GIVE_UP,
    }

    /**
     * @param blockedBy 电脑回执里的 `blocked_by`,没有就传空串。
     * @param confirmedSent 这一次动作**已经带着「他点过头」的凭证发过一轮了吗**。
     *
     * ★★ 三条里最要紧的是 [Tap.GIVE_UP] 那一支:**同一件事绝不问第二遍**。
     *   问第二遍的代价不是「烦」—— 是他会开始**闭着眼点**,而一个被闭着眼点的
     *   确认框等于没有。到那一步,这三层闸就退化成了让人烦躁的动画。
     */
    internal fun tapNext(blockedBy: String, confirmedSent: Boolean): Tap = when {
        // ★ 用**精确相等**,不用 contains。别的失败原因(`lost_focus` / `type_failed` /
        //   `search_not_typed` …)说的是完全另一回事;把它们也当成「要你点头」,
        //   他会对着一个「字打到别的窗口去了」的故障白点一次头,而真正的原因被埋掉。
        blockedBy != NEEDS_CONFIRM -> Tap.PASS
        confirmedSent -> Tap.GIVE_UP
        else -> Tap.ASK_THEN_RETRY
    }

    /**
     * 为什么这一轮一路都要点头 —— 写给他看的**原因**,让他知道该嫌谁烦。
     *
     * @param word [matchedWord] 命中的那个词。
     */
    internal fun whyHighTier(word: String): String =
        "你这句里提到了「$word」,所以这一轮里她每动一次鼠标键盘,我都会先问你一下"
}
