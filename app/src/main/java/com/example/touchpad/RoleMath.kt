package com.example.touchpad

/**
 * **按任务内容选角色。**
 *
 * 以前派出去只有一种人：`算`。于是「帮我把这段话改短」也会派给一个「算」的助手，
 * 它拿到的自我介绍是「你是算」，做的事却是润色 —— 角色名和活对不上，
 * 提示词里那几行约束就白写了。
 *
 * ## ★ 2026-11-05：名字改成**岗位**，不再是单个动作字
 *
 * 他的原话是「agent 的名字要改，不能写成什么算、什么的」。他说得对：
 * 「算」「改」是一个**动作**，不是一个人。派出去的那位拿到的第一句话是
 * 「你是算」——那不是职务，那是个指令碎片。换成「估算师」「编辑」「审稿人」之后，
 * 同一句自我介绍才读得通，也才看得出这个人**负责哪一段**。
 *
 * 另有一条：拆解时可以起**更细**的一次性岗位名（比如「报价核算」「条款挑刺」）——
 * 一个人干一件事，或者干一件事里更细的一段，两种都行。见 [brief]。
 *
 * 这里用一张**按活分类**的表，从任务文本里挑最贴的几个名字。纯关键词，不调模型：
 * - 选错一个角色的代价只是称呼不顺，不会算错；
 * - 但它换来的是**拆解时有据可依** —— 云端拆活时能看见「这件事适合编辑、审稿人」，
 *   而不是自己编几个「角色1、角色2」。
 *
 * ★ 表里的名字同时是**技能沉淀**（见 [SkillMath]）的索引词，改名会让旧草稿技能
 *   对不上号（它们只是草稿，不影响任何正在跑的东西）。
 */
object RoleMath {

    data class Role(val name: String, val job: String, val triggers: List<String>)

    /**
     * 角色表。顺序即同分时的优先顺序 —— 越靠前越通用。
     *
     * ★ 每条的名字是**岗位**（三个字，说得清是谁），[Role.job] 是**他负责的那一段活**。
     * ★ 触发词是给 [pick] 用的，纯包含匹配，别写成需要断词的短语。
     */
    val ROLES: List<Role> = listOf(
        Role(
            "估算师", "粗算、估个数、比大小",
            listOf("算", "估", "多久", "多少", "几成", "几倍", "成本", "耗时", "大概要", "性价比"),
        ),
        Role(
            "检索员", "找依据、核事实、给来源",
            listOf("查", "搜", "依据", "出处", "来源", "是不是真", "有没有这回事", "资料", "规定"),
        ),
        Role(
            "审稿人", "挑毛病、说哪里站不住、唱反调",
            listOf("挑", "毛病", "问题在", "站不住", "反驳", "风险", "漏洞", "不行", "缺点", "翻车", "坑"),
        ),
        Role(
            "编辑", "改写、润色、缩短、换语气",
            listOf("改", "润色", "改写", "缩短", "精简", "扩写", "换个说法", "书面", "正式一点", "通顺"),
        ),
        Role(
            "举例员", "给具体例子、给反例",
            listOf("举例", "例子", "比如", "示范", "样例"),
        ),
        Role(
            "规划师", "拆步骤、排先后、给方案",
            listOf("计划", "步骤", "怎么做", "方案", "规划", "流程", "下一步"),
        ),
        Role(
            "讲解员", "讲清原因和原理",
            listOf("为什么", "原理", "解释", "怎么回事", "什么意思", "原因"),
        ),
        // ★ 兜底那位**故意没有触发词**：它永远不会被 [pick] 挑中（命中数恒为 0），
        //   只在「什么都没命中」时由 [FALLBACK] 点名。放在这里只是为了让 [jobOf] 查得到它。
        Role(
            "研究员", "什么活都接：把这件事本身想清楚，给结论和依据",
            emptyList(),
        ),
    )

    /**
     * 默认角色 —— 什么都没命中时用它。
     *
     * ★ 不再是「算」：一个润色任务交给「估算师」是错的，而交给「研究员」
     *   （把这件事想清楚并给结论）至少不错。它不该是个具体动作。
     */
    const val FALLBACK = "研究员"

    /**
     * 按任务挑角色，最多 [max] 个，最贴的在前。
     *
     * ★ 命中不了任何触发词就回**空表**，不硬凑 —— 调用方该退回 [FALLBACK]。
     *   硬凑一个「审稿人」给「把这句话翻译成英文」只会让提示词更乱。
     */
    fun pick(text: String, max: Int = 3): List<String> {
        if (text.isBlank() || max <= 0) return emptyList()
        val scored = ROLES.mapIndexedNotNull { idx, r ->
            val hits = r.triggers.count { text.contains(it) }
            if (hits <= 0) null else Triple(r.name, hits, idx)
        }
        return scored
            // 命中多的在前；同分按表里的顺序（越通用越靠前）。
            .sortedWith(compareByDescending<Triple<String, Int, Int>> { it.second }.thenBy { it.third })
            .take(max)
            .map { it.first }
    }

    /** 角色名 → 它的职责说明（给拆解提示词用）。认不出来的角色回 null。 */
    fun jobOf(name: String): String? = ROLES.firstOrNull { it.name == name }?.job

    /**
     * 拆解提示词里那段「能用的角色」。
     *
     * ★ 只在表里挑 3 个当**建议**，并且明说「也可以用别的」——
     *   把角色的口子焊死，遇到这张表覆盖不到的活，拆解就会硬套。
     * ★★ 2026-11-05 起还加了一句**要起细的**：他明说「一个 agent 可以干一件事里
     *   更细的一段」。表里那七个是**通用岗位**，遇到具体活（报价、条款、封面图）
     *   现起一个更贴的名字，比硬套「研究员」强得多。
     */
    fun brief(text: String): String {
        val picked = pick(text, 3).ifEmpty { listOf(FALLBACK) }
        return "这件事适合的角色有：" + picked.joinToString("、") { n ->
            jobOf(n)?.let { "$n（$it）" } ?: n
        } + "。也可以按这件活起更细的名字，两到六个字，一看就知道它负责哪一段" +
            "（例如「报价核算」「条款挑刺」「封面对齐」）。"
    }
}
