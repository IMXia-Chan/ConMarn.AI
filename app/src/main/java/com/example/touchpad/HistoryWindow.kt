package com.example.touchpad

/**
 * 一份对话历史**什么时候裁、裁掉多少**。
 *
 * ★★ 2026-10-05 立的。用户报的症状是「响应时间太久了」,真凶在这一行算术里。
 *
 * ## 老规矩(`len > 12 就 remove(0),一直保持 12`)为什么是灾难
 *
 * llama-server 复用 KV 缓存靠的是**从头开始的最长公共前缀**,源码里就一句
 * (`tools/server/server-context.cpp`):
 *
 * ```cpp
 * n_past = slot.prompt.tokens.get_common_prefix(input_tokens);
 * ```
 *
 * **是前缀,不是子串。** 所以只要提示词**开头**那几个 token 变了,后面全白算。
 *
 * 老规矩每轮做的是:加 2 条新的、从**队首**去掉 2 条最旧的。一旦聊满 6 轮,
 * **每一轮都会动队首** —— 于是这一轮的提示词和上一轮存下的
 * `[system][工具表][历史…]` 只在 `[system][工具表]` 这截相同,
 * **整段历史每一轮都要从零重算**。
 *
 * 那要多久:`[system][工具表]` 实测 4889 token、冷算 212 秒;历史几百 token,
 * 按降频时的 23 token/秒也要十几到几十秒。而读超时
 * ([AiAgent.Config.localDeadlineMs])只有 **25 秒**。
 *
 * 于是每一轮都:
 *
 * ```
 * 发出请求 → 服务端闷头重算历史(一个字节都不往外吐) → 25 秒到 → 判定「本地算得慢」
 *          → 转云端 → 这一轮没在本地跑成 → 槽里的缓存**没有前进** → 下一轮一模一样
 * ```
 *
 * **死循环,而且是静默的** —— 日志上只有一行「本地算得慢(降频或这一轮算得多),转云端…」,
 * 读起来像偶发的性能问题,其实是**每一轮都必然发生**,跟温度没关系。
 *
 * ## 所以规矩改成「涨到 MAX 才裁,一裁裁到 KEEP」
 *
 * ```
 *   4 ──涨──────────────────────────────► 20   裁!  ──► 4 ──涨──► …
 *   ←────── 这 8 轮里提示词只往后追加,前缀一直命中 ──────►
 * ```
 *
 * 两次裁剪之间提示词**只追加、不动头**,缓存前缀完整保住 —— 那几轮里本地只要算
 * **新说的那一句话**(几十个 token,一两秒)。
 *
 * 裁剪那一下仍然要重算(留下的那截是老序列的**后缀**,不是前缀,保不住),
 * 但那一下的账是 `KEEP` 条消息、不是 12 条,而且**八轮才付一次**。
 *
 * ## 为什么 KEEP 给这么小
 *
 * 裁一次要重算的就是留下来的这截。25 秒这道墙在那儿,**留下的越多、那一下越可能撞墙**。
 * KEEP = 4 时留下约两三百 token,降频最狠的时候也只要十几秒,还在这道墙以内。
 *
 * 代价说清楚:**刚裁完那一小会儿她只记得最近两轮**。平均记忆(6 轮)和从前一样,
 * 只是从「恒为 6」变成了「2 涨到 10」——这是拿记忆的**波动**换延迟的**稳定**,
 * 而那正是用户要的(「响应时间太久了」)。
 *
 * ★ 别把它调成「len >= MAX 就裁」:`saveTurn` 一轮加 2 条,判等会让它每隔一轮裁一次,
 * 又滑回老路。**判据必须是「超过」**。
 */
internal object HistoryWindow {

    /**
     * 涨到这个条数以上就裁一次。
     *
     * 20 条 = 10 轮对话。这个数是「记忆够不够用」和「裁剪多频繁」之间的取舍 ——
     * 它越大裁得越少(前缀越稳),但越接近 8192 的上下文上限。
     * 前缀 4889 + 20 条消息(约 1200)+ 工具轮 + 生成,还在 8192 里面。
     */
    internal const val MAX = 20

    /**
     * 裁一次之后留多少条。**4 条 = 最近两轮**。
     *
     * 见文件头「为什么 KEEP 给这么小」——它直接决定裁剪那一下要重算多少。
     */
    internal const val KEEP = 4

    /**
     * 这一份历史(共 [len] 条)现在该从队首去掉几条。**0 = 不用裁。**
     *
     * 单独抽出来是因为它错了**不报任何错**:裁多了只是她变健忘,裁少了只是变慢,
     * 而「每轮都裁」和「八轮才裁」在日志里长得几乎一样。钉它得靠单测。
     */
    internal fun dropCount(len: Int): Int = if (len > MAX) len - KEEP else 0
}
