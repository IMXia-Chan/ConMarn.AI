package com.example.touchpad

/**
 * 玻璃胶囊上那句**占位话**最短要在屏幕上待多久。
 *
 * ★★ 2026-10-05 用户报的:
 *   > 「房间语音输入结束会在透明磨砂玻璃中跳出个提示,**太快了我看不清是什么**」
 *   —— 那句话是 [ConMarnActivity.HINT_DECODING]「**在认你说的话…**」。
 *
 * ## 它为什么会闪过去
 *
 * 松手之后有两件事**比赛**:一句占位话(「在认你说的话…」)和转写结果(他自己的话)。
 * 占位话的职责是填住松手到定稿之间的空档 —— 屏幕在那一段里空着的话,
 * 他刚说完一句最重要的话却什么都没看见,看起来像**白说了**,然后他会再说一遍。
 *
 * 可是这个「空档」**多长全看转写有多快**:
 *   · 转写慢(常见)就有两秒,那句话看得清清楚楚;
 *   · 转写快(短句、模型热着)只有两三百毫秒 —— 那句话**一闪而过**,
 *     快到他连写的是什么都没看清,只留下「刚才好像跳了个东西」的印象。
 *
 * 一句话只要**存在过却读不到**,它就不是提示,是噪音。
 *
 * ## 所以规矩是「最短停留」,不是「一定显示」
 *
 * 真话**不丢**,只是**排队**等一会儿([ConMarnActivity.deferredCaption])。
 * 1.2 秒是「够读完八个汉字」和「察觉不到有等待」之间的那条线。
 *
 * ★ 为什么抽出来单测:这段算术只有一行,但**它错了不会报错** ——
 *   错了的表现是「那句话还是一闪而过」,而那正是这次要修的东西,
 *   看着像「改了没用」。钉住边界(正好到点、刚好差一点、时钟跳了)比事后肉眼靠谱。
 */
internal object CaptionDwell {

    /**
     * 占位话至少停留多久(毫秒)。
     *
     * ★ 1200 是量出来的、不是拍的:八个汉字按正常阅读速度约 0.9 秒,
     *   再留一点点余量。别往上加 —— 加多了他真的会感觉到「她怎么半天没反应」,
     *   而那句占位话本身就是在解释「我在忙,别急」,解释太久就变成新的抱怨点。
     */
    internal const val MIN_MS = 1200L

    /**
     * 一句**真话**来了,占位话该不该先顶住?
     *
     * @param placeholderShowing 字幕上现在是不是占位话(不是占位就别拦,让真话立刻上)。
     * @param sinceMs            那句话**被写上去**的时刻(墙上时间)。
     * @param nowMs              现在。
     * @return 真话还要等多少毫秒;**0 = 现在就可以显示**。
     */
    internal fun waitMs(placeholderShowing: Boolean, sinceMs: Long, nowMs: Long): Long {
        if (!placeholderShowing) return 0
        val shownFor = nowMs - sinceMs
        // ★ 负数是**时钟被重设过**(或 sinceMs 还没写成)。
        //   拿它减出来的会是个远大于 MIN_MS 的等待 —— 表现是字幕**卡死在占位话上**,
        //   真话永远不上来,而那看起来像「她没听见」。宁可不拦(0),让它立刻上。
        if (shownFor < 0) return 0
        return (MIN_MS - shownFor).coerceAtLeast(0)
    }
}
