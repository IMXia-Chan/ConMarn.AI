package com.example.touchpad

/**
 * ★★ **她那行字要多大、最多折几行** —— 从「这一句有多长」算出来的纯函数,零 Android 依赖。
 *
 * ## 为什么有这个东西(用户 2026-10-05 当场报的)
 *
 * 原话:
 *
 * > 「然后,**最后是以省略号的形式出现**,那太不好了,所以,**要么把字做小一点,
 * >  不然不能全显示出来**」
 *
 * 病根在 `ConMarnActivity` 里 `herSay` 那两个写死的属性:
 * `maxLines = 3` + `ellipsize = TruncateAt.END` —— 那是 2026-10-05 下午
 * 「从单行横向滚动改成折行」时一起收的(当时是为了治「隐藏到一半后面没法显示」)。
 * **三行 + 省略号治好了「看不见后半截」,但没治好「看不见最后那一句」** ——
 * 她现在整段回答超过三行的时候,末尾就变成一个 `…`,而那正是他真正要读的那部分。
 *
 * ## 解法的形状(他自己给的两个选项,这里**两个都做**)
 *
 * 他给了两条路:「把字做小一点」或者「不能全显示出来」(= 让它装得下)。
 * **这两条不冲突,合起来才是完整的**:
 *
 * * **字随长度收小** —— 短的照旧 16,长的自动降到 12 上下;
 * * **天花板从 3 行抬到 [MAX_LINES]** —— 折行空间多了两倍多。
 *
 * 光抬行数不收字,长回答会「占一大片屏」(他 2026-10-05 下午的另一条抱怨);
 * 光收字不抬行数,三行装不下的还是装不下。**两个一起动,长句才既装得下又不铺满屏。**
 *
 * ## ★ 为什么必须是纯逻辑
 *
 * 「多长的句子该用多大字」是一件**能判定**的事,而这个项目的老规矩是能判定的事
 * 一律零 Android 依赖、必须能 JVM 单测([MoodMath] / [GreetMath] / [EarMath] /
 * [SpeechMath] / [QuietMath] 全是这个形状 —— **不能单测的代码在这里等于不可信**)。
 *
 * 这条尤其要紧:它错了**不报错**,只表现成「字幕又被切了」或者「字幕占满屏」,
 * 两种都要靠肉眼撞见。[CaptionFitTest] 逐档钉住。
 *
 * ## ★ 边界
 *
 * 它只回答两个问题:**这一句该用多大字**([textSize])、**最多给它几行**([MAX_LINES])。
 * 什么时候写这一行、写谁的话、亮还是灭 —— **全在调用方**,它一个都不知道。
 */
internal object CaptionFit {

    /**
     * 一行字幕**最多**折几行。
     *
     * ★★ **这是天花板,不是目标。** `herSay` 的高度是 `WRAP_CONTENT`,
     * 一句短话就只占一行 —— 把天花板抬高**不会**让短话变高。
     * 它只在长句上起作用,而那正是要治的那一格。
     *
     * 取值:3 → 7。配上 [textSize] 的收字,实测口径下(横屏满宽约 815dp)
     * 一句 400 字上下的回答也装得下。
     */
    const val MAX_LINES = 7

    /**
     * 收到这个字号就**不再收**。
     *
     * 它防的是「极长的回答把字缩成看不清的一团」—— 那种情况下
     * 末尾那个省略号反而是**诚实的**(它在说「这里还有,我装不下了」)。
     * ★ **宁可见得见的省略号,不要看不清的满屏小字。**
     */
    const val MIN_TEXT_SIZE = 9f

    /**
     * 这一句该用多大字。
     *
     * @param base 不带长度时的字号 —— **由调用方给**,因为它身上还挂着另一层意思:
     *             她定稿的话是 16、他说的和她的草稿是 14(见 `ConMarnActivity` 里
     *             那三个调用点)。★ 那一层区分是**既有设计**,这一层只在它之上**收小**,
     *             绝不越过它去改「谁大谁小」。
     * @param chars 这一句**最终**多长(不是「已经显示了几个字」——
     *              按最终长度算,打字过程中才不会一路缩水)。
     */
    fun textSize(base: Float, chars: Int): Float = when {
        chars <= 40 -> base
        chars <= 80 -> base - 1f
        chars <= 130 -> base - 2f
        chars <= 200 -> base - 3f
        else -> base - 4f
    }.coerceAtLeast(MIN_TEXT_SIZE)

    /**
     * 这一句最多给几行。
     *
     * 现在是个常量 —— 留着这个函数是为了**调用方只有一处**(`fitHerSay`),
     * 以后要按长度分档(比如短句只给 2 行、逼它早点收字)只动这里,不动界面。
     */
    fun maxLines(chars: Int): Int = MAX_LINES
}
