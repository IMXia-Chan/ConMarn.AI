package com.example.touchpad

/**
 * 「她这一句是什么语气」→「她该做哪条动作」。
 *
 * ---------------------------------------------------------------------------
 * ★★ 用户 2026-10-17 的原话:
 *
 *   > 「我想知道,agent 她现在语气能不能和动作匹配,这是我现在想做的」
 *
 * 2026-10-09 他第一次提的时候补了一句「我也不做现在,你只需要帮我先记一下」——
 * **那条已经解除了**,就是现在做。
 *
 * ---------------------------------------------------------------------------
 * 今天之前,这条链是**断的**,而且断得很干净:
 *
 * | 环 | 今天什么样 |
 * |---|---|
 * | 读语气 | ✅ [ConMarnActivity.emotionOf] 已经在算,吐五个词之一 |
 * | 用它 | ❌ 只有 `setEmotion('$emo', 0.75)` —— **只驱动脸** |
 * | 动作 | ✅ `Her.setMotion(url)` 能播,但只有两个触发:进房间 / 动作栏手挑 |
 *
 * 所以这个对象补的是**中间那一环**:一张表 + 一个「现在该不该换」的判断。
 * 真正把动作推下去的那行在 [ConMarnActivity.fireEmotionMotion]。
 *
 * ---------------------------------------------------------------------------
 * ★ 为什么表里**只出现 `vrm-viewer/` 那几条**(用户没问,但不写下来会有人好心改坏):
 *
 * 动作库有三个来源,授权不一样(见 `motion-library/README.txt`):
 *
 * - `vrm-viewer`(tk256ailab)**MIT** —— 11 条情绪动作,全部 3.93s / 119 帧,最整齐的一套;
 * - `vroid-official`(pixiv)**禁止以可提取形式再分发** ⇒ **不能进公开仓库,也不能打进 APK**;
 * - `voxavatar`(xikhar)**MIT** —— 种类杂,但没有「情绪」这一档。
 *
 * → ★★ 所以情绪表**天然只能落在这 11 条里**,而它正好三条名字直接对得上
 *   (`angry` / `sad` / `surprised`)。**这条表给出去不会踩任何授权线** ——
 *   这是白捡的,别换成 pixiv 那 7 条。
 *
 * ---------------------------------------------------------------------------
 * ★★ 表里的内容是他的人设,不是我的默认值
 *
 * 同 [conmarn-persona-is-his-to-tune]:**她哪种语气配哪条动作,是她的性格,他填。**
 *
 * 2026-10-17 他看完第一版(五个语气全配了动作)当场改了两处 ——
 * 「**笑不要那个动作**」/「**嘴巴动就行了**」/「**不要这么故意,不是什么话都要动作的**」。
 * 落地就是 [SILENT]:笑只动脸和嘴,兜底档不再摆动作。**剩下的三个保留**,他没否。
 *
 * ---------------------------------------------------------------------------
 * ★★★ 为什么需要 [shouldFire](这一步不做,画面上就是「抽搐」)
 *
 * `Her.setMotion` 的实现是**先把上一条 `stop()` 掉再装新的**(见 her.js 里那段注释的
 * 理由:两条动作同时跑 = 一组骨头被两个方向扯)。而她是**按句念**的
 * (切句抢先音,见 `SpeechChunkMath`)—— 一段话会触发好几次 `startTalking`。
 *
 * 于是「她连说三句带情绪的话」= 动作被抢三次、每次从第 0 帧重来 = **看着像抽搐**。
 *
 * → 判据:**上一条动作还在播,这一次就不换。**
 *   把它做成一个**时间间隔**而不是「去问 JS 播完没有」,是因为下面这条:
 *
 *   `vrm-viewer` 那 11 条**全部 3.93 秒**(119 帧 @ 30fps,逐条量过)。
 *   所以「距上一次推动作已经超过 4.2 秒」等价于「上一条已经播完了」,
 *   而且**不需要一次 JS 往返、不需要一个可能永远不来的回调**。
 *
 *   ★ 这正是这个项目最怕的那类失败的反面:`onMotionDone` 万一不来(文件坏 / JS 没回调 /
 *     动作压根没播),「等回调」那套会让**她再也不推动作,而且一个字都不报**。
 *     用表上的数,最坏情况只是「这一次没换」。
 *
 *   ★ 代价要说白:哪天换了一条**比 4.2 秒长**的动作进来,它在播的时候会被打断一次。
 *     那时把 [MIN_GAP_MS] 改成那条动作的真实时长。
 */
internal object EmotionMotionMath {

    /** 情绪动作所在的子目录。库根由 [Wardrobe.motionLibraryDir] 给。 */
    internal const val DIR = "vrm-viewer"

    /**
     * 五个语气词里,**会动身体的那三个** → 动作文件名(不含目录、不含扩展名)。
     *
     * ★ 另外两个(`happy` / `relaxed`)在 [SILENT] 里,是**他点名不许动**的,不是漏了。
     *   写成两个集合、而不是「这一格留空」,差别很重要:
     *   「她不动」从此能一眼看出是**他的决定**,而不是**谁把那一行删了**。
     */
    internal val TABLE: Map<String, String> = mapOf(
        "sad" to "Sad",
        "surprised" to "Surprised",
        "angry" to "Angry",
    )

    /**
     * 这几个语气**故意不动身体**。
     *
     * ★★★ 用户 2026-10-17 两句话定的,原样留着:
     *
     *   > 「**笑不要那个动作**」→ 我追问换成哪条,他补:**「嘴巴动就行了」**
     *   > 「**然后不要这么故意,不是什么话都要动作的**」
     *
     * 两句合起来正好落两格:
     *
     * - **`happy`(笑)** —— 表情照做、口型照做(**那两样本来就一直在跑**),
     *   身体**一下都不动**。他在乎的是「笑一下不必配一个抬手鼓掌」。
     *
     * - **`relaxed`** —— ★ 它是 [ConMarnActivity.emotionOf] 的**兜底档**
     *   (`else -> "relaxed"`)。它真正的意思不是「她现在很放松」,是
     *   **「这句话里没听出情绪」**。以前它配着 `Relax.vrma` ⇒ **她随便回一句都要摆个动作**
     *   —— 那正是他说的「太故意」。
     *
     * ★ 这一格**最容易被人好心改坏**:`relaxed` 看起来像「她该有个放松的动作」,
     *   而它其实是「没有情绪的默认值」。要动它先读上面这两句原话。
     */
    internal val SILENT: Set<String> = setOf("happy", "relaxed")

    /**
     * 这个语气是不是**故意不动**。
     *
     * 调用方据此**静静返回**(不记日志)—— 因为它和「表里没这个词」是两件事:
     * 前者是他定的行为,后者是表和 `emotionOf` 对不上了、**必须报**。
     */
    internal fun isSilent(emotion: String): Boolean =
        SILENT.contains(emotion.trim().lowercase())

    /**
     * 两次推动作之间至少隔多久(毫秒)。
     *
     * ★ 4200 = vrm-viewer 那 11 条的 3.93 秒 + 一点余量。**理由见文件头。**
     */
    internal const val MIN_GAP_MS = 4_200L

    /**
     * 这个语气该做哪条动作。返回**库里相对路径**(如 `vrm-viewer/Sad.vrma`)。
     *
     * 返回 null 有**两种**,调用方必须先 [isSilent] 分开:
     * - 在 [SILENT] 里 = **他定的不动**,静静返回就对了;
     * - 其余 = 这个词**既不动、也没被登记成不动** ⇒ 表和 `emotionOf` 对不上了,**要报**。
     *
     * ★ 把这两种混成一种,症状是「日志里天天报一句假警报」,而假警报一多,
     *   真警报就没人看了。
     */
    internal fun relativePath(emotion: String): String? {
        val what = TABLE[emotion.trim().lowercase()] ?: return null
        return "$DIR/$what.vrma"
    }

    /**
     * 这一次该不该推动作。
     *
     * @param nowMs      现在(`SystemClock.elapsedRealtime()`,**不是墙上时间** ——
     *                   这个项目吃过「跨机器比 `at`」的亏,而这里本来就不需要绝对时间)
     * @param lastFireAtMs 上一次推动作的时刻;从没推过给 0 或负数
     *
     * ★ `lastFireAtMs <= 0` 一律放行,而且**不能**靠「`now - 0 > 4200`」碰巧成立:
     *   开机不到 4.2 秒时 `now` 就是个三位数,那样第一条动作会被吃掉,且没有任何征兆。
     *   [EmotionMotionMathTest.刚开机四秒内也放行第一条] 钉着它。
     */
    internal fun shouldFire(
        nowMs: Long,
        lastFireAtMs: Long,
        gapMs: Long = MIN_GAP_MS,
    ): Boolean {
        if (lastFireAtMs <= 0L) return true
        // 时钟被回拨 / 算错(now 比上次还早)= 不信这个间隔,直接放行。
        // 宁可多播一次,也不要因为一个坏数把动作**永久**锁死。
        if (nowMs < lastFireAtMs) return true
        return nowMs - lastFireAtMs >= gapMs
    }
}
