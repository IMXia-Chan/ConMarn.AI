package com.example.touchpad

/**
 * 「她手上还有活的时候,你又说了一句」—— **纯逻辑,零 Android 依赖,能跑 JVM 单测。**
 *
 * ## 它治的是什么
 *
 * 她跑着的时候你说话,原来**话是直接丢掉的** —— 她会回一句「上一轮还在跑,先点停止」,
 * 你得先手动点「停止」、等它退出来、再把同一句话重说一遍。
 * 用户把这个叫做「**打断不了她**」,而它根本不是取消逻辑不对,是**新消息进不来**。
 *
 * 所以现在的做法是:不丢。**叫停 → 等它松手 → 接手**。
 *
 * ## 为什么「等」这件事要单独有个名字
 *
 * 因为等待有两个方向都要命的错法,而它们各自都不报错:
 *
 * | 错法 | 症状 |
 * |---|---|
 * | **等得不够久** | 旧任务还没退就接手 → 两轮同时跑(两双手抢同一只鼠标) |
 * | **一直等下去** | 你说的话卡在后台,永远没有回音 —— 又回到了「被丢掉」,只是更难查 |
 *
 * 所以这里的每一条都是**上下界**,不是「大概」:
 *
 * - **下界 = 一次工具调用的上限。** 她的「停」不是瞬时的:跨机器那一步靠轮询才检查得到
 *   (见 `AiAgent.callPc` 里那个 200ms),所以**最坏情况就是一个工具跑完为止**。
 *   等的时间短于这个数,等于在她**最需要停一下**的时候抢先开跑。
 * - **上界 = 那个数再加一点余量。** 到点还没停,就不接手了,但**必须出声**
 *   (见 [gaveUp])—— 静默地把她的话吃掉,正是这条要修的东西。
 *
 * ## 两条要说给用户听的话,也在这里
 *
 * [calledOut] / [gaveUp] 是**用户会看到的字**,所以它们和判定住在同一个对象里,
 * 由单测钉住 —— 钉的不是文采,是两条不许违反的规矩:
 *
 * 1. ★★ **不许承诺「我一动她就停」。** 一次点击在 Windows 上 350ms 就落地了,
 *    没有 OS 级钩子收不回来。要说「她停下来了,但**刚才那一下可能已经发生**」。
 * 2. ★ **不许把「没接手」说成「没事」。** 话没送出去就得明说没送出去。
 */
internal object HandoffMath {

    /** 等的时候隔多久看一眼她松开手没有。**不长不短**:50ms 对人是即时的,也不烧电。 */
    internal const val POLL_MS = 50L

    /** 一次工具调用的默认上限 —— 和 `AiAgent.config.toolTimeoutMs` 的初值对齐。 */
    internal const val DEFAULT_TOOL_TIMEOUT_MS = 25_000L

    /**
     * 那个数上面再加的余量。
     *
     * ★ 它买的不是「工具跑得更久」,是**旧任务退出本身**要花的时间:
     *   `checkCancel()` 抛出 → 异常往上冒 → `finally` 里清 pending、收忙闲标志。
     *   这些是毫秒级,但要留够,不能让「已经停了、只差最后两行」被判成停不下来。
     */
    internal const val MARGIN_MS = 5_000L

    /**
     * 最多等多久。
     *
     * ★★ **它必须大于一次工具调用的上限** —— 这条不是风格,是这条功能的全部意义:
     *   她的「停」要等当前那个工具跑完才生效,等的时间短于这个数,
     *   我们就会在她**最该停一下**的那次调用上放弃。
     *
     * [toolTimeoutMs] 传 0 或负数时退回默认值 —— 配置坏掉不该让等待变成零,
     * 那正是「等得不够久」那一行。
     */
    internal fun waitCapMs(toolTimeoutMs: Long): Long =
        (if (toolTimeoutMs > 0) toolTimeoutMs else DEFAULT_TOOL_TIMEOUT_MS) + MARGIN_MS

    /**
     * 还能接着等吗。
     *
     * 用**半开区间**:到了上限就是不能等(和 `QuietMath` 那条免打扰同一套写法 ——
     * 「整点」算哪边,必须只有一个答案)。
     */
    internal fun mayKeepWaiting(elapsedMs: Long, capMs: Long): Boolean = elapsedMs < capMs

    /**
     * 她手上还有活、我准备叫停接手时,说给你的那句话。
     *
     * ★★ **这一句是「手要诚实」的落点**:他按下去的那一刻,电脑上可能已经有一击落地了。
     *   说「马上停」是撒谎,而撒谎的代价他付不起 —— 那一下可能是转账。
     */
    internal fun calledOut(): String =
        "她手上还有活,我先叫停 —— 已经按下去的那一下收不回来,但后面不会再做了。你这句我记着"

    /**
     * 等过头了、这一句没接手时说的话。
     *
     * ★ **必须明说「没送出去」**,不能只说「卡住了」—— 否则你以为它在跑,
     *   干等一个永远不会来的回答。(「静默失败」在这个项目里是头号敌人。)
     *
     * @param waitedMs 实际等了多久,用来给出一个人能核对的时间。
     */
    internal fun gaveUp(waitedMs: Long): String {
        val sec = (waitedMs / 1000L).coerceAtLeast(1L)
        return "她上一轮卡住了,等了 ${sec} 秒也没停下来 —— 你刚才那句我没敢塞进去,待会儿再说一次"
    }
}
