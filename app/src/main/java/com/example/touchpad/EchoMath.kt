package com.example.touchpad

/**
 * 「引擎报回来的这条回调,是谁的回声」—— **纯逻辑,零 Android 依赖,能跑 JVM 单测。**
 *
 * ## 它治的是什么
 *
 * 她每说一句,TTS 都会给这一句发一个号,念完带着号回调回来。问题出在**她改口**的时候:
 *
 * > 说到一半被打断 / 被新的一句顶掉(房间里是 `QUEUE_ADD`,悬浮窗那条是 `QUEUE_FLUSH`)
 * > → 旧那一句**还是会回调**,而且**有早有晚**。
 * > → 那条迟到的回调一到,我们当成「**当前这句**念完了」→ 把麦克风放回去。
 * > → 而此刻她**正在说新的那句**,扬声器出来的声音绕回自己的麦 → **自问自答**。
 *
 * 这和 [EarSessionMath] 里那些坑是同一族:**不报错、日志干净**,
 * 唯一的表现是「她把自己说的话当成你说的话」。
 *
 * ## 判据只有一条,但**每一条分支的代价不对称**
 *
 * | 判错的方向 | 后果 |
 * |---|---|
 * | **认错一条**(把别人的回声当成自己的) | 麦克风提前开 → **自问自答** |
 * | **漏认一条**(自己的回声没认出来) | 只是**多等一会儿** —— 两处都有兜底闹钟 |
 *
 * 所以整条规则往「不认」那边倒:
 *
 * - **号不一样 ⇒ 不是我们的。** 号是她自己发的,不存在「长得像」这种情况;
 * - **没带号(`null`)⇒ 也不是我们的。** 全项目每一处 `speak()` 都传了号
 *   (`HerVoice.kt` / `ConMarnActivity.kt` 各一处) —— 所以一条**不带号**的回调
 *   只可能来自我们自己没排过的那句话。★ 这不是推测,是把所有调用点数过一遍的结论;
 * - ★★ **`current == null` 时,谁的回声都不算。** 这一条同时管三件事:
 *   已经兑现过了(幂等)、刚被 [stop] 过、还没开始念 —— 三种情况都是「没什么可结束的」。
 *
 * ## 反过来的那半句:兜底闹钟**不走这道闸**
 *
 * 上面那张表里「漏认一条」之所以只是「多等一会儿」,是因为两处各有一个按字数估的兜底
 * (`HerVoice` 的 `backstop`、房间里 `onFinal` 那道 [EarSessionMath.speechWaitMs])。
 * ★ 那两个兜底是**「再等下去就是卡住了」**,不是「大概等这么久」——
 * 它们存在的理由恰恰是**引擎一声都不吭**,所以它们**必须能绕过这道闸**。
 * 谁要是把闸也加到兜底上,就等于把「引擎不说话」重新变回「她永远不理我」。
 */
internal object EchoMath {

    /**
     * 引擎刚报的这条回调,是不是**我们正在等的那一条**。
     *
     * @param reported 回调里带的号(引擎可能不报,那就是 `null`)。
     * @param current  我们**正在等**的那条号;`null` = 没在等。
     */
    internal fun isOurs(reported: String?, current: String?): Boolean =
        current != null && reported == current
}
