package com.example.touchpad

/**
 * 「按住那块玻璃」这件事里**不该靠猜**的两个判断。
 *
 * ## 为什么值得单独一个文件
 *
 * 房间里和悬浮条上用的是**同一个手指、同一块玻璃、同一套手势** ——
 * 用户 2026-10-05 原话把两处一起点了名:
 *
 * > 「我要的是**按住对话框说话**,不是右边弄个麦克风按钮…**点对话框**就会是打字模式,
 * >   到打字模式后如果还想回语音输入模式,就再点麦克风…**松开对话框就是发送**…
 * >   如果在语音输入的时候不想发送,需要重说或者取消发送,**就往上滑**」
 *
 * 两处各写一份的话,「上滑取消」这一个判断就有两份实现 —— 而它错起来的样子是
 * **那句话还是送出去了**(不可逆),或者**明明没滑够却取消了**(他白说一遍)。
 * 这个项目在「同一个 bug 修两次」上吃过好几回,所以判据收在这儿一份。
 *
 * ## 上滑取消的取向:从严
 *
 * [release] 的**第一条**就是 `swipeCancelled`。这跟 [EarSessionMath.isExitPhrase]
 * 「宁可漏不可错」是**反的**,而且是故意的 —— 因为这两件事不可逆的那一侧不同:
 *
 * | 判断 | 错了的代价 | 所以取向 |
 * |---|---|---|
 * | 挂断词认不认 | 认错 = 对话突然断掉 | **宁可漏**(漏了只是多聊一轮) |
 * | 上滑取不取消 | 不认 = **说出口的话已经发出去了** | **宁可从严**(多取消一次,他重说一遍就行) |
 *
 * 这一条在代码里的落法是一个**闩**:手指一进取消区就置位,哪怕他最后又滑回来了,
 * 这一次也**认取消**。做成「松手时现算距离」的话,有那么几十毫秒他以为已经取消、
 * 松手之后话却出去了 —— 而那正是这一整套手势里唯一退不回来的那一步。
 */
internal object BarGestureMath {

    /**
     * 往上滑多少算「不要了」。
     *
     * ★ 56dp 是**手感**,不是安全边界:小一点会更灵敏、更容易误取消,
     *   大一点会变成「我明明滑了却没取消」。房间里一直是这个数,搬过来不改。
     *   ⚠️ 换算成像素要用**当时那块屏**的 density(见调用处的 `dp()`),
     *     这里收的是**已经换算好的像素值**,好让这个对象不碰 Android。
     */
    const val CANCEL_SWIPE_DP = 56

    /** 手指松开时,这一下到底算什么。 */
    enum class Release {
        /** 上滑取消了 —— **录音要扔,那句话一个字节都不许送出去**。 */
        CANCEL,

        /** 点一下。落在哪儿由调用方判(她正在说 → 打断;她安静 → 进打字)。 */
        TAP,

        /** 按住说完了 —— 松手即「我说完了」,当场收尾转写。 */
        HOLD,
    }

    /**
     * 手指**往上**走了 [thresholdPx] 没有。
     *
     * ★★ 只认往上。往下滑在这里**没有含义** —— 多解释一个方向就多一种误取消,
     *   而误取消的代价是他白说一遍。房间里那条注释写得很清楚(见 [ConMarnActivity]
     *   的 `onCaptionTouch`),这里照抄。
     *
     * ★ 边界取 `>=`:正好滑到门槛就算数。和 [EarSessionMath.sessionOver] 同一个规矩 ——
     *   边界在测试里要钉得死,不能一半用 `>` 一半用 `>=`。
     *
     * @param downRawY 按下那一刻的原始 Y(屏幕坐标,**不是**相对某个 View 的)
     * @param nowRawY 现在的原始 Y
     */
    fun entersCancelZone(downRawY: Float, nowRawY: Float, thresholdPx: Float): Boolean =
        downRawY - nowRawY >= thresholdPx

    /**
     * 松手 = 这一下算什么。
     *
     * ★★ [swipeCancelled] **排在第一个**,不是「最后再看」——
     *   一个只按了 60ms 的上滑(比 [EarSessionMath.TAP_MAX_MS] 短得多)照样是取消,
     *   **不能落到 `TAP` 上去**。不然「我滑了一下想撤,结果它当成点一下,进了打字模式」
     *   就会发生,而那句话可能已经在上滑之前被 [Ear.finishNow] 送出去了。
     *
     * @param swipeCancelled 手指**进过**取消区(闩,不是当前距离)
     * @param heldMs 从按下到松开的毫秒数
     */
    fun release(swipeCancelled: Boolean, heldMs: Long): Release = when {
        swipeCancelled -> Release.CANCEL
        EarSessionMath.isTap(heldMs) -> Release.TAP
        else -> Release.HOLD
    }
}
